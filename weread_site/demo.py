def _book(
    title: str,
    authors: list[str],
    categories: list[str],
    *,
    status: str,
    rating: float,
    my_rating: int,
    seconds: int,
    days: int,
    words: int,
    intro: str,
    started: str,
    finished: str | None,
    last_read: str,
    highlights: list[tuple[str, str, str, str]],
    publisher: str = "",
    published: str = "",
    isbn: str = "",
) -> dict[str, Any]:
    source_id = f"demo-{title}"
    return {
        "source_id": source_id,
        "slug": stable_slug(title, source_id),
        "title": title,
        "authors": authors,
        "categories": categories,
        "cover": None,
        "isbn": isbn,
        "publisher": publisher,
        "published": published,
        "rating": rating,
        "my_rating": my_rating,
        "status": status,
        "status_label": {"finished": "读完", "reading": "在读", "want": "想读"}[status],
        "progress": 1.0 if status == "finished" else (0.62 if status == "reading" else 0.0),
        "reading_seconds": seconds,
        "reading_time_label": reading_time_label(seconds),
        "reading_days": days,
        "words": words,
        "price": None,
        "intro": intro,
        "link": "",
        "started_at": started,
        "finished_at": finished,
        "last_read_at": last_read,
        "highlight_count": len(highlights),
        "note_count": sum(1 for item in highlights if item[3]),
        "chapter_count": len({item[0] for item in highlights}),
        "highlights": [
            {
                "kind": "note" if note else "highlight",
                "text": text,
                "note": note,
                "chapter": chapter,
                "created_at": created,
            }
            for chapter, text, note, created in highlights
        ],
    }


def _demo_daily() -> list[dict[str, Any]]:
    today = date(2026, 11, 12)
    rows: list[dict[str, Any]] = []
    for offset in range(365, -1, -1):
        day = today - timedelta(days=offset)
        digest = hashlib.sha1(day.isoformat().encode()).digest()
        if digest[0] % 10 < 6:
            seconds = 120 + (digest[1] * 11 + digest[2] * 17) % 1200
            rows.append({"date": day.isoformat(), "seconds": seconds})
    return rows


