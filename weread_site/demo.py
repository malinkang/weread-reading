def write_demo(path) -> None:
    import json
    from pathlib import Path

    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(demo_snapshot(), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


